export type MessageKey = keyof (typeof messages)['pt-BR']

export function pickLang(tag: string | undefined): Lang {
  const lower = (tag ?? '').toLowerCase()
  if (lower.startsWith('pt')) return 'pt-BR'
  if (lower.startsWith('es')) return 'es'
  return 'en'
}

let current: Lang = pickLang(typeof navigator === 'undefined' ? undefined : navigator.language)

export function setLang(lang: Lang) {
  current = lang
}

export function getLang(): Lang {
  return current
}

export function t(key: MessageKey): string {
  return messages[current][key]
}

/** The locale for dates and money in the current language. */
export function locale(): string {
  return current
}

export const ALL_MESSAGES = messages
