"""Records who changed what, as a side effect of saving.

A SQLAlchemy `after_flush` listener looks at every object the session just
wrote. For the models in `AUDITED` it inserts one `audit_events` row per
created, changed or deleted object, in the same transaction: if the change
rolls back, so does its trail; if it commits, the trail is there.

Nothing in a route has to remember to call this, which is the point. A new
route that writes an audited model is covered on day one. A new *model* is not
silently missed either: `tests/test_audit_coverage.py` fails until it is listed
here as audited or as exempt, with a reason.

Who did it comes from `audit_context`, a request-scoped value filled in by the
middleware (address, browser, request id) and by the authentication dependency
(the user). Outside a request (Celery, scripts) there is no actor and the event
is recorded as `system`.
"""
