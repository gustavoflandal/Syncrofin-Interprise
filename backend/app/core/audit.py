# Never written to the trail, not even masked.
_OMITTED = {"raw_data", "embedding"}

# Written as "***" (the fact that it changed is kept, the value is not). Checked by column name across
# every audited model, so a name only belongs here when EVERY audited model that has it wants it hidden.
# `detail`/`resolution_note` are unique to `DataSubjectRequest` among `AUDITED` models (`ReconciliationEvent`
# and `AuditEvent` also have a `detail` column, but neither is audited by this mechanism — both are listed
# in `EXEMPT` — so there is no collision). `email` is NOT here: `Group` and `Payee` also carry a legitimate,
# non-account e-mail that a workspace's own audit trail should keep showing; only `User.email` is masked,
# via the model-aware check in `_shown` below (the same pattern `AppSetting` already uses).
_MASKED = {
    "hashed_password",
    "totp_secret",
    "totp_secret_enc",
    "totp_backup_codes",
    "credentials",
    "api_key_encrypted",
    "share_token",
    "public_key",
    "credential_id",
    "storage_key",
    "token_hash",
    "detail",
    "resolution_note",
}

# Columns that change on their own, constantly. A row whose only changes are these is not an event.
_NOISE: dict[type, set[str]] = {
    Account: {"balance", "balance_primary"},
    BankConnection: {"last_sync_at"},
    User: {"failed_login_count", "lock_count", "last_failed_login_at", "locked_until"},
}

_MAX_TEXT = 2000
_ENTITY: dict[type, str] = {model: cast(str, getattr(model, "__tablename__")) for model in AUDITED}
_TABLE = cast(Table, AuditEvent.__table__)

#: The table names of `AUDITED`, for the coverage test.
AUDITED_TABLES = frozenset(_ENTITY.values())
_AUDITED = frozenset(AUDITED)


def _json_value(value: Any) -> Any:
    """Something a JSONB column accepts, whatever the column held."""
    if value is None or isinstance(value, (bool, int, float)):
        return value
    if isinstance(value, Decimal):
        return str(value)
    if isinstance(value, (datetime, date, time)):
        return value.isoformat()
    if isinstance(value, uuid.UUID):
        return str(value)
    if isinstance(value, enum.Enum):
        return _json_value(value.value)
    if isinstance(value, str):
        return value if len(value) <= _MAX_TEXT else value[:_MAX_TEXT] + "…"
    if isinstance(value, (bytes, bytearray, memoryview)):
        return f"<{len(value)} bytes>"
    if isinstance(value, dict):
        return {str(k): _json_value(v) for k, v in value.items()}
    if isinstance(value, (list, tuple, set)):
        return [_json_value(v) for v in value]
    return str(value)


_SECRETISH = ("password", "secret", "token", "key")


def _raw(obj: Any, name: str) -> Any:
    """The attribute as loaded, never triggering a load: this runs in the middle of a flush."""
    return inspect(obj).dict.get(name)


def _shown(obj: Any, column: str, value: Any) -> Any:
    if column in _MASKED:
        return None if value is None else "***"
    # An instance setting is a key/value pair: mask by what the key says it holds.
    if isinstance(obj, AppSetting) and column == "value" and any(w in str(_raw(obj, "key")).lower() for w in _SECRETISH):
        return None if value is None else "***"
    # The account's own e-mail, model-aware rather than by column name alone: `Group.email` (an invited
    # member's contact address) and `Payee.email` (a vendor's contact address) are legitimate business
    # records that a workspace's own audit trail should keep showing in the clear.
    if isinstance(obj, User) and column == "email":
        return None if value is None else "***"
    return _json_value(value)


def _changes(obj: Any, action: str) -> dict[str, list[Any]] | None:
    """{column: [before, after]} for what this flush did to the object."""
    state = inspect(obj)
    model = type(obj)
    result: dict[str, list[Any]] = {}
    for attr in state.mapper.column_attrs:
        key = attr.key
        if key in _OMITTED:
            continue
        history = attributes.get_history(obj, key, passive=attributes.PASSIVE_NO_INITIALIZE)
        if action == "create":
            value = history.added[0] if history.added else _raw(obj, key)
            if value is not None:
                result[key] = [None, _shown(obj, key, value)]
        elif action == "delete":
            value = history.unchanged[0] if history.unchanged else (history.deleted or [None])[0]
            if value is not None:
                result[key] = [_shown(obj, key, value), None]
        elif history.has_changes():
            before = history.deleted[0] if history.deleted else None
            after = history.added[0] if history.added else None
            if before != after:
                result[key] = [_shown(obj, key, before), _shown(obj, key, after)]
    if action == "update":
        meaningful = set(result) - _NOISE.get(model, set())
        if not meaningful:
            return None
    return result


def _workspace_of(obj: Any) -> uuid.UUID | None:
    if isinstance(obj, Workspace):
        return _raw(obj, "id")
    return _raw(obj, "workspace_id")


def _entity_id(obj: Any) -> str:
    """The primary key, whatever the column is called. (A row inserted in this very flush has no
    identity key yet, so it is read off the instance, not off `inspect(obj).identity`.)"""
    return "/".join(str(part) for part in inspect(obj).mapper.primary_key_from_instance(obj))


def _row(obj: Any, action: str, changes: dict[str, list[Any]]) -> dict[str, Any]:
    ctx = current_context()
    return {
        "id": uuid.uuid4(),
        "actor_user_id": ctx.actor_user_id,
        "actor_kind": ctx.actor_kind,
        "workspace_id": _workspace_of(obj),
        "action": action,
        "entity_type": _ENTITY[type(obj)],
        "entity_id": _entity_id(obj),
        "changes": changes,
        "ip": ctx.ip,
        "user_agent": (ctx.user_agent or "")[:300] or None,
        "request_id": ctx.request_id,
        # Which token, when it was one: the person behind it is `actor_user_id`.
        "detail": f"api_token:{ctx.api_token_prefix}" if ctx.api_token_id else None,
    }


def _after_flush(session: Session, flush_context: Any) -> None:
    rows: list[dict[str, Any]] = []
    for obj in session.new:
        if type(obj) in _AUDITED:
            changes = _changes(obj, "create")
            rows.append(_row(obj, "create", changes or {}))
    for obj in session.dirty:
        if type(obj) in _AUDITED and session.is_modified(obj):
            changes = _changes(obj, "update")
            if changes:
                rows.append(_row(obj, "update", changes))
    for obj in session.deleted:
        if type(obj) in _AUDITED:
            rows.append(_row(obj, "delete", _changes(obj, "delete") or {}))
    if rows:
        session.connection().execute(insert(_TABLE), rows)


def install_audit() -> None:
    """Idempotent: one listener on every session."""
    if not event.contains(Session, "after_flush", _after_flush):
        event.listen(Session, "after_flush", _after_flush)


install_audit()


async def record_event(
    session: Any,
    action: str,
    entity_type: str,
    *,
    entity_id: Any = None,
    workspace_id: uuid.UUID | None = None,
    detail: str | None = None,
    changes: dict[str, Any] | None = None,
) -> None:
    """A named event that is not a row change ("export", "login failed")."""
    ctx = current_context()
    await session.execute(
        insert(_TABLE).values(
            id=uuid.uuid4(),
            actor_user_id=ctx.actor_user_id,
            actor_kind=ctx.actor_kind,
            workspace_id=workspace_id,
            action=action,
            entity_type=entity_type,
            entity_id=str(entity_id) if entity_id is not None else None,
            changes=_json_value(changes) if changes else None,
            ip=ctx.ip,
            user_agent=(ctx.user_agent or "")[:300] or None,
            request_id=ctx.request_id,
            detail=detail,
        )
    )


async def seal(session: Any) -> int:
    """Chain every row that is not sealed yet. Returns how many were sealed."""
    sealed = (await session.execute(text("SELECT audit_events_seal()"))).scalar_one()
    await session.commit()
    return int(sealed)
